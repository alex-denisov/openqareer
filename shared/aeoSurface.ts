function tariffLine(): string {
  return TARIFF_LEVELS.map((level) => `${level.name} ${level.price}`).join(', ');
}

function bullet(lines: readonly string[]): string {
  return lines.map((line) => `- ${line}`).join('\n');
}

/** Source records are not deduplicated vacancies. Keep that distinction beside every count. */
function poolEvidence(stats?: LandingStats): string[] {
  if (!stats) return [];
  return [
    '## Срез пула',
    '',
    `Дата наблюдения: ${stats.updatedAt}.`,
    `Активных записей источников: ${stats.activeCount}; удалённых записей: ${stats.remoteCount}; источников: ${stats.sourceCount}.`,
    'Источник: vacancy_pool_index, is_active = 1 и expired = 0; плановый пересчёт фоновым заданием каждые 30 минут.',
    'Одна вакансия может встречаться на нескольких площадках: записи могут повторяться. Это не число уникальных вакансий или результат проверки каждой позиции у работодателя.',
    '',
  ];
}

/** Короткий индекс витрины — то, что ответчик читает первым. */
export function buildLlmsTxt(stats?: LandingStats): string {
  const legal = LEGAL_DOCS.map(
    (doc) => `- [${doc.title}](${SITE_ORIGIN}${legalPath(doc.slug)})`,
  ).join('\n');
  return [
    '# openqareer',
    '',
    `> ${SUMMARY}`,
    '',
    `- Canonical product: [openqareer.com](${SITE_ORIGIN}/)`,
    '- Language: Russian',
    `- Audience: ${AUDIENCE}`,
    '- Product boundary: openqareer не обещает интервью, оффер, трудоустройство или визу',
    `- Vacancy catalogue: ${SITE_ORIGIN}/vacancies`,
    `- Remote vacancies: ${SITE_ORIGIN}/vacancies/remote`,
    `- Country Fit employee payroll calculator: ${SITE_ORIGIN}/tools/country-fit (2026 data; user-entered expenses; not tax advice)`,
    `- Pricing: ${tariffLine()}`,
    `- Updated: ${AEO_UPDATED_AT}`,
    `- Full specification: ${SITE_ORIGIN}/llms-full.txt`,
    '',
    ...poolEvidence(stats),
    '## Помощь',
    '',
    `- [Вопросы и ответы о поиске работы](${SITE_ORIGIN}/faq)`,
    `- [Поддержка](${SITE_ORIGIN}/support)`,
    '',
    '## Правовые документы',
    '',
    legal,
    '',
  ].join('\n');
}

/** Полная спецификация: факты, границы и адреса, без пересказа маркетинга. */
export function buildLlmsFullTxt(stats?: LandingStats): string {
  const legal = LEGAL_DOCS.map(
    (doc) => `- [${doc.title}](${SITE_ORIGIN}${legalPath(doc.slug)}) — ${doc.description}`,
  ).join('\n');
  return [
    '# openqareer — полная спецификация',
    '',
    `> ${SUMMARY}`,
    '',
    `Обновлено: ${AEO_UPDATED_AT}.`,
    '',
    ...poolEvidence(stats),
    '## Что это',
    '',
    'openqareer — рабочее место кандидата, которым владеет сам кандидат. Оно превращает',
    'доказательства из его опыта, гипотезы ролей, наблюдения рынка и результаты откликов',
    'в объяснимый цикл следующего действия. Это не доска вакансий, не бот массовых откликов',
    'и не только генератор сопроводительных писем.',
    '',
    `Аудитория: ${AUDIENCE}`,
    '',
    '## Что продукт делает',
    '',
    bullet(CAPABILITIES),
    '',
    '## Чего продукт не делает',
    '',
    bullet(BOUNDARIES),
    '',
    '## Как устроен доступ',
    '',
    '- Тариф Free бесплатен и не ограничен по сроку. Платные тарифы — помесячная подписка:',
    bullet(
      TARIFF_LEVELS.map(
        (level) =>
          `${level.name} — ${level.price}${level.term ? ` ${level.term}` : ''}: ${level.promise}`,
      ),
    ),
    '- Веб-приложение на openqareer.com; профили с площадок (LinkedIn, hh.ru и другие) подключаются в приложении для компьютера.',
    '- Данные кандидата можно выгрузить и удалить вместе с аккаунтом в настройках.',
    '',
    '## Откуда берутся вакансии',
    '',
    '- Прямые ATS-доски компаний: Greenhouse, Lever, Ashby, Workable, Recruitee.',
    '- Открытые ленты и агрегаторы удалённой работы.',
    '- Каждая карточка называет источник и дату наблюдения; повторы с разных площадок сводятся в одну запись.',
    '- Площадка с непроверенным адресом помечается, а не выдаётся за рабочую.',
    '',
    '## Правовые документы',
    '',
    legal,
    '',
    '## Адреса',
    '',
    bullet(AEO_PUBLISHED_PATHS.map((path) => `${SITE_ORIGIN}${path === '/' ? '/' : path}`)),
    '',
  ].join('\n');
}
