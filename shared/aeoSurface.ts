/**
 * Витрина для ИИ-поисковиков: `/llms.txt` и `/llms-full.txt` (B209).
 *
 * ПОЧЕМУ ГЕНЕРАТОР, А НЕ ФАЙЛ В `public/`. Ручной `public/llms.txt` жил
 * отдельно от продукта и устаревал молча: ни один тест не связывал его
 * содержание с тем, что приложение действительно умеет. Здесь витрина
 * собирается из тех же данных, что и правовой пакет, а тесты держат её в
 * границах продукта — без обещаний работы и без непроверяемых превосходных
 * степеней. Ответчику (Яндекс Нейро, Google AI Overviews, Perplexity,
 * ChatGPT) нужны факты и границы, а не маркетинг.
 */
import { LEGAL_DOCS, legalPath } from './legalRegistry';

export const SITE_ORIGIN = 'https://openqareer.com';

/** Каждый публичный адрес, который витрина имеет право назвать. */
export const AEO_PUBLISHED_PATHS: readonly string[] = [
  '/',
  ...LEGAL_DOCS.map((doc) => legalPath(doc.slug)),
];

/** Что продукт делает — только то, что уже работает в выпущенной сборке. */
const CAPABILITIES: readonly string[] = [
  'Разбирает резюме кандидата из PDF и собирает профиль по фактам: опыт, результаты, навыки, образование.',
  'Импортирует профиль LinkedIn и резюме hh.ru через десктопное приложение, в сессии самого кандидата.',
  'Показывает карьерную диагностику: на какие роли уже есть опора в опыте и каких данных не хватает для решения.',
  'Проверяет гипотезу роли на датированной выборке вакансий из подключённых источников.',
  'Собирает пул вакансий с ATS-досок компаний (Greenhouse, Lever, Ashby, Workable, Recruitee) и открытых лент.',
  'Сводит одну и ту же вакансию с нескольких площадок в одну карточку и называет канонический источник.',
  'Предлагает одно следующее действие, объясняет его причину и показывает, что изменится после выполнения.',
  'Даёт выгрузку и удаление данных кандидата вместе с аккаунтом.',
];

/** Границы. Ответчик, который их не знает, придумает их сам. */
const BOUNDARIES: readonly string[] = [
  'Не кадровое агентство и не работодатель: решение о найме принимает компания.',
  'Не обещает интервью, оффер, трудоустройство или визу.',
  'Не рассылает отклики массово и не действует в аккаунтах кандидата без его подтверждения.',
  'Не продаёт и не передаёт данные кандидата работодателям.',
  'Не инструмент наблюдения за кандидатом для работодателя: продуктом владеет сам кандидат.',
  'Покупка подписки и автоматизация внешних аккаунтов в продукте пока не подключены.',
];

const AUDIENCE =
  'Кандидаты, которые проверяют карьерное направление, ищут работу в России и за рубежом, ' +
  'рассматривают релокацию или удалённую работу с оплатой в валюте.';

const SUMMARY =
  'Карьерная операционная система кандидата: профиль по фактам, гипотезы ролей, наблюдения рынка, ' +
  'карьерный трек и подготовленные действия для поиска работы.';

function bullet(lines: readonly string[]): string {
  return lines.map((line) => `- ${line}`).join('\n');
}

/** Короткий индекс витрины — то, что ответчик читает первым. */
export function buildLlmsTxt(): string {
  const legal = LEGAL_DOCS.map(
    (doc) => `- [${doc.title}](${SITE_ORIGIN}${legalPath(doc.slug)})`,
  ).join('\n');
  return [
    '# openqareer',
    '',
    `> ${SUMMARY}`,
    '',
    `- Canonical product: [openqareer.com](${SITE_ORIGIN}/)`,
    '- Language: Russian',
    `- Audience: ${AUDIENCE}`,
    '- Product boundary: openqareer не обещает интервью, оффер, трудоустройство или визу',
    `- Full specification: ${SITE_ORIGIN}/llms-full.txt`,
    '',
    '## Правовые документы',
    '',
    legal,
    '',
  ].join('\n');
}

/** Полная спецификация: факты, границы и адреса, без пересказа маркетинга. */
export function buildLlmsFullTxt(): string {
  const legal = LEGAL_DOCS.map(
    (doc) => `- [${doc.title}](${SITE_ORIGIN}${legalPath(doc.slug)}) — ${doc.description}`,
  ).join('\n');
  return [
    '# openqareer — полная спецификация',
    '',
    `> ${SUMMARY}`,
    '',
    '## Что это',
    '',
    'openqareer — карьерная операционная система, которой владеет кандидат. Она превращает',
    'доказательства из его опыта, гипотезы ролей, наблюдения рынка и результаты откликов',
    'в объяснимый цикл следующего действия. Это не доска вакансий, не бот массовых откликов',
    'и не генератор сопроводительных писем.',
    '',
    `Аудитория: ${AUDIENCE}`,
    '',
    '## Что продукт делает',
    '',
    bullet(CAPABILITIES),
    '',
    '## Чего продукт не делает',
    '',
    bullet(BOUNDARIES),
    '',
    '## Как устроен доступ',
    '',
    '- Базовый тариф бесплатен и не ограничен по сроку.',
    '- Веб-приложение на openqareer.com; импорт из LinkedIn и hh.ru — через десктопное приложение.',
    '- Данные кандидата можно выгрузить и удалить вместе с аккаунтом в настройках.',
    '',
    '## Откуда берутся вакансии',
    '',
    '- Прямые ATS-доски компаний: Greenhouse, Lever, Ashby, Workable, Recruitee.',
    '- Открытые ленты и агрегаторы удалённой работы.',
    '- Каждая карточка называет источник и дату наблюдения; повторы с разных площадок сводятся в одну запись.',
    '- Площадка с непроверенным адресом помечается, а не выдаётся за рабочую.',
    '',
    '## Правовые документы',
    '',
    legal,
    '',
    '## Адреса',
    '',
    bullet(AEO_PUBLISHED_PATHS.map((path) => `${SITE_ORIGIN}${path === '/' ? '/' : path}`)),
    '',
  ].join('\n');
}
