const FIRST_PERSON = /(?<!\p{L})(?:я|мы|мне|меня|мной|мой|моя|моё|мои|моего|моей|моих|наш\p{L}*|у меня|i|i['’](?:ve|m)|we|we['’]ve|my|our)(?!\p{L})/iu;
const OWN_VERB = /(?<!\p{L})\p{L}{3,}(?:ал|ил|ял|ёл|ел|ёс|ую|юю|жу|шу|чу|щу|усь|юсь)(?:а|и|ся|сь)?(?!\p{L})/iu;
const PLAN = /(?<!\p{L})(?:i['’](?:d|ll)|i would|i will|let['’]s|happy to|glad to|готов\p{L}*|предлагаю|обсудим|давайте|расскажу|созвонимся|буду|хотел бы|хотела бы)(?!\p{L})/iu;
const PLACE_OR_NUMBER = /\d/u;
/** Обобщение об опыте не называет действия и первого лица может не иметь: «This is familiar ground». */
const EXPERIENCE = /(?<!\p{L})(?:(?:по|из|на) опыт\p{L}*|опыт\p{L}*|знаком\p{L}*|привычн\p{L}*|карьер\p{L}*|десятилети\p{L}*|годами|на практике|experience\p{L}*|familiar|career|decades?|years?|track record|background)(?!\p{L})/iu;

/** Номера предложений об опыте кандидата: мнения о задаче работодателя и планы модель не читает. */
export function claimSentenceNumbers(sentences: readonly string[], employers: readonly string[]): number[] {
  return sentences.flatMap((sentence, index) => {
    if (EXPERIENCE.test(sentence)) return [index + 1];
    if (PLAN.test(sentence)) return [];
    const aboutCandidate = FIRST_PERSON.test(sentence) || OWN_VERB.test(sentence) ||
      PLACE_OR_NUMBER.test(sentence) || employers.some((employer) => sentence.includes(employer));
    return aboutCandidate ? [index + 1] : [];
  });
}

export interface LetterFix {
  readonly n: number;
  readonly text: string;
}

/** Заменяет предложения прямо в тексте, чтобы остальной письмо и абзацы остались как есть. */
export function applyLetterFixes(body: string, sentences: readonly string[], fixes: readonly LetterFix[]): string {
  return fixes.reduce((text, fix) => {
    const sentence = sentences[fix.n - 1];
    return sentence ? text.replace(sentence, () => fix.text.trim()) : text;
  }, body);
}

