/**
 * B681/B750: шаблоны задачи System Design. Область по описанию вакансии (`DOMAINS`),
 * семья роли по названию (`FAMILIES`) и общий запасной (`CORE_API`). У каждого — название,
 * четыре пункта «Что важно в задаче» (I3a) и строки образца ответа по критериям разбора.
 */

export interface TaskSpec {
  /** Что проектируем — в тексте условия, с маленькой буквы. */
  readonly service: string;
  /** Заголовок экрана. */
  readonly title: string;
  readonly scope: string;
  /** Ровно четыре пункта: так в макете i03a. */
  readonly points: readonly [string, string, string, string];
  readonly requirements: string;
  readonly components: string;
  readonly tradeoff: string;
  readonly operations: string;
}

export interface DomainSpec extends TaskSpec {
  readonly keywords: readonly string[];
}

