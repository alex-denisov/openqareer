import { describe, expect, it } from 'vitest';
import { distortedWords } from './letterWordDistortion';

const SOURCES = [
  'Корпоративный университет Сбера, ИТ-функция кампуса. Руководитель направления.',
  'ИТ Лидер кластера в Сбер. Опыт с ЦОД и ВКонтакте, работа с 1С:ERP.',
];

describe('distortedWords (B640): искажения слов профиля и вакансии в письме GLM', () => {
  it('сбой регистра в слове из профиля или вакансии: «СБером»', () => {
    expect(distortedWords('С СБером меня связывает многолетний опыт.', SOURCES)).toEqual(['СБером']);
  });

  it('обрезанное окончание: «руководител», «заместител»', () => {
    expect(distortedWords('Я руководител технологическими подразделениями.', SOURCES)).toEqual(['руководител']);
    expect(distortedWords('Был заместител директора.', [])).toEqual(['заместител']);
  });

  it('слово без мягкого знака, которое есть в источниках с ним', () => {
    expect(distortedWords('Работал в Корпоративном университете Сбера как руководител.', SOURCES)).toEqual([
      'руководител',
    ]);
  });

  it.each([
    'С компанией меня связывает работа в Корпоративном университете Сбера.',
    'Знаю специфику ЦОДа и ВКонтакте изнутри.',
    'Я хотел бы обсудить роль. Команда летела к цели.',
    'Руководитель направления, ИТ-лидер, CSAT вырос с 23% до 68%.',
    'Working at Sber Corporate University, I built the IT function.',
    'Внедрил 1С:ERP и SLA-мониторинг; МГУ, ВУЗ, ИПБ России.',
    // Ложные срабатывания на 538 прежних письмах (снятое правило «то же слово с ь/й»).
    'Отдельно отмечу отдельной строкой: процесс закрыт, чтобы закрыть риски; работает стабильно и стабильной.',
    'Технически это технический долг; практически успешно, задаче с задачей, просто и простой.',
  ])('без искажений: %s', (body) => {
    expect(distortedWords(body, SOURCES)).toEqual([]);
  });
});
