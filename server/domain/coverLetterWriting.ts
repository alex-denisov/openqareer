export const COVER_LETTER_PROMPT = `Помоги коллеге. Напиши от лица кандидата сопроводительное сообщение на языке вакансии по вакансии ниже. Получатель: {RECIPIENT}. Род кандидата: {GENDER}. Резюме приложено к этому сообщению.

Тон: профессиональный, спокойный и уважительный. Так сильный специалист или руководитель пишет незнакомому человеку в компании, а не другу. Уверенность идёт от фактов, а не от заявлений о себе. Кандидат не торопит и не ставит условий, не говорит, что хочет получить роль, и не рассказывает компании, как будет работать и что будет делать на новом месте.

Пиши на профессиональном языке того направления, куда подаётся кандидат, и с учётом того, кто будет читать. Термины и принятые в этой области обозначения уместны, если их знает такой читатель. Если получатель неизвестен или это общая почта, считай, что письмо прочитает профильный специалист этого направления.

Начни с приветствия, по имени, если оно известно. Затем короткий вводный абзац: на какую вакансию в какой компании кандидат откликается и в одной-двух фразах кто он и что сильнее всего связывает его с этой вакансией и компанией. Читатель должен с первых строк понять, о какой вакансии речь и почему стоит читать дальше.

Письмо компактное, около 150–180 слов, но без потери сути: это не пересказ резюме. Если фактов кандидата на такой объём не хватает, пиши короче: обязанности из вакансии не выдавай за его опыт. Дальше возьми только три-четыре самых важных для этой вакансии опыта, остальные опусти. Бери их из двух-трёх мест работы, а не из всех подряд, если вакансия сама не просит весь путь. Располагай их по важности для вакансии, самое важное первым, а не по времени. Покажи каждый фактами: что сделал и что это дало. Короткие абзацы или список выбери сам, смотря что читается лучше.

Называй компании, а должности не называй. Каждая мысль один раз, без повторов.

Про технологии можно сказать, как кандидат работает с ними сейчас, если это есть в профиле. Если какого-то требования вакансии в его опыте нет или совпадение неполное, просто не поднимай эту тему и не оправдывайся. Единственное исключение: вакансия прямо называет это обязательным условием.

В конце скажи, что резюме приложено, и вежливо предложи обсудить, чем кандидат может быть полезен в самых важных задачах этой роли. Закончи без давления. Подпись и «с уважением» не пиши, их добавит система. В тексте не должно быть заглушек в квадратных скобках.

Опирайся только на профиль и уточнения кандидата. Цифры не меняй и разные цифры в одну не соединяй. Факты, которых там нет, не добавляй, в том числе об интересах кандидата и о том, за чем он следит. Соблюдай порядок событий: что было раньше, а что позже, не называй одновременным.

Вакансия:
{VACANCY}

Профиль кандидата:
{PROFILE}

Верни только текст сообщения.
`;

/**
 * Ограничитель от сбоя модели, а не от длинного письма: принятые письма 1030–1380 знаков, в LinkedIn
 * длинные проходят. Больше этого письмом не считается, и очередь спрашивает следующую ступень: обрезка
 * убрала бы конец, где сказано про резюме.
 */
export const COVER_LETTER_MAX_CHARS = 3000;

export type LetterGender = 'male' | 'female';

export interface CoverLetterPromptInput {
  readonly vacancy: string;
  readonly profile: string;
  readonly recipient?: { readonly name?: string; readonly role?: string };
  /** По имени из профиля (`candidateGender.ts`); если определить нельзя, род в письме не виден. */
  readonly gender?: LetterGender;
  /** Только когда кандидат выбрал язык сам; иначе язык письма определяет вакансия. */
  readonly chosenLanguage?: 'en' | 'ru';
  /** `false` — опыта работы нет, резюме к отклику не приложится, и письмо его не упоминает (B601, 08.11). */
  readonly resumeAttached?: boolean;
  /** Имя из профиля как есть; модель возвращает его на языке письма для подписи и темы (B624). */
  readonly candidateName?: string;
  /** B639: место кандидата в компании вакансии или её группе (`letterCompanyLink`). */
  readonly companyLink?: string;
  /** B640: причина отказа проверки — отдельным абзацем после утверждённого запроса. */
  readonly correction?: string;
}

/**
 * Без резюме утверждённый запрос не просит сказать о приложении. Меняются только фразы про резюме,
 * остальной текст запроса тот же: он утверждён дословно и сверяется по хешу.
 */
const NO_RESUME_EDITS: readonly (readonly [string, string])[] = [
  [' Резюме приложено к этому сообщению.', ' Резюме к сообщению не приложено, не упоминай его.'],
  ['это не пересказ резюме', 'это не пересказ профиля'],
  ['В конце скажи, что резюме приложено, и вежливо предложи', 'В конце вежливо предложи'],
];

/**
 * B624: имя для подписи переводит модель. Утверждённый запрос не меняется: заменяется только
 * последняя фраза, и только когда имя в профиле есть.
 */
const RETURN_TEXT_ONLY = 'Верни только текст сообщения.';

function withSignatureName(template: string): string {
  return template.replace(
    RETURN_TEXT_ONLY,
    `Верни текст сообщения. После него отдельной последней строкой напиши «${SIGNATURE_LINE_LABEL} » и имя и фамилию кандидата (в профиле: {NAME}) так, как их пишут на языке сообщения: сначала имя, потом фамилия.`,
  );
}

/**
 * B639: работа в компании вакансии — сильнейший довод письма, и после правки длины модель его теряла.
 * Утверждённый запрос не меняется: фраза добавляется только при совпадении (`letterCompanyLink`).
 */
const INTRO_SENTENCE_END = 'что сильнее всего связывает его с этой вакансией и компанией.';

function withCompanyLink(template: string): string {
  return template.replace(
    INTRO_SENTENCE_END,
    `${INTRO_SENTENCE_END} Кандидат работал в «{LINK}»: это та же компания, что в вакансии, или её группа. Обязательно скажи об этом во вводном абзаце как о том, что связывает его с компанией, даже если письмо выйдет длиннее 180 слов или мест работы станет больше. Если по тексту вакансии видно, что это другая компания, не говори об этом.`,
  );
}

function withoutResume(template: string): string {
  return NO_RESUME_EDITS.reduce((text, [from, to]) => text.replace(from, to), template);
}

const GENDER_TEXT: Readonly<Record<LetterGender, string>> = { male: 'мужской', female: 'женский' };
/** Запрос утверждён дословно, поэтому просьба не показывать род идёт значением, а не правкой текста. */
const UNKNOWN_GENDER_TEXT = 'не указан, пиши так, чтобы род кандидата не был виден';
const LANGUAGE_TEXT: Readonly<Record<'en' | 'ru', string>> = {
  en: 'на английском языке',
  ru: 'на русском языке',
};

function recipientText(recipient: CoverLetterPromptInput['recipient']): string {
  const parts = [recipient?.name, recipient?.role].flatMap((part) => (part?.trim() ? [part.trim()] : []));
  return parts.length > 0 ? parts.join(', ') : 'неизвестен';
}

/** За один проход: фигурные скобки и `$&` в тексте вакансии остаются текстом. */
export function coverLetterPrompt(input: CoverLetterPromptInput): string {
  const name = input.candidateName?.trim();
  const values: Readonly<Record<string, string>> = {
    RECIPIENT: recipientText(input.recipient),
    GENDER: input.gender ? GENDER_TEXT[input.gender] : UNKNOWN_GENDER_TEXT,
    VACANCY: input.vacancy.trim(),
    PROFILE: input.profile.trim(),
    NAME: name ?? '',
    LINK: input.companyLink?.trim() ?? '',
  };
  const approved = input.resumeAttached === false ? withoutResume(COVER_LETTER_PROMPT) : COVER_LETTER_PROMPT;
  const signed = name ? withSignatureName(approved) : approved;
  const linked = input.companyLink?.trim() ? withCompanyLink(signed) : signed;
  const template = input.chosenLanguage
    ? linked.replace('на языке вакансии', LANGUAGE_TEXT[input.chosenLanguage])
    : linked;
  const prompt = template.replace(/\{(RECIPIENT|GENDER|VACANCY|PROFILE|NAME|LINK)\}/gu, (_match, key: string) => values[key] ?? '').trim();
  const correction = input.correction?.trim();
  return correction ? `${prompt}\n\n${correction}` : prompt;
}
