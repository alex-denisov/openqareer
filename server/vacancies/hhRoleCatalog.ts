/** Категория «Информационные технологии» — набор ролей по умолчанию. */
export const HH_IT_CATEGORY_ID = '11';

export const DEFAULT_SELECTED_ROLE_IDS: readonly string[] =
  HH_ROLE_CATEGORIES.find((category) => category.id === HH_IT_CATEGORY_ID)?.roles.map(
    (role) => role.id,
  ) ?? [];

const ROLE_INDEX: ReadonlyMap<string, HhRole> = new Map(
  HH_ROLE_CATEGORIES.flatMap((category) => category.roles.map((role) => [role.id, role])),
);

export function findHhRole(roleId: string): HhRole | undefined {
  return ROLE_INDEX.get(roleId);
}

/**
 * Оставляет только те роли, которые площадка действительно знает. Выдуманный
 * идентификатор в фильтре превратил бы обход в тихо пустой запрос, а продукт
 * обязан отличать «ничего не нашлось» от «спросили несуществующее» (B161).
 */
export function keepKnownRoleIds(roleIds: readonly string[]): string[] {
  const seen = new Set<string>();
  return roleIds.filter((id) => {
    if (seen.has(id) || !ROLE_INDEX.has(id)) return false;
    seen.add(id);
    return true;
  });
}
