/**
 * Generates the alias tables under ./generated from freehire's Go source
 * (internal/dict/classify, MIT, Copyright (c) 2026 freehire contributors).
 *
 *   npx tsx server/vacancies/titleParse/freehireClassify/generateTables.ts <freehire>/internal/dict/classify
 *
 * Entries keep the exact declaration order of each Go slice; the concatenation
 * order of the slices is fixed in ../freehireClassify/tables.ts, as in classify.go.
 * Read-only on the Go side; writes only ./generated/*.ts.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

interface TableSpec {
  readonly goFile: string;
  readonly goVar: string;
  readonly tsName: string;
}

const CORE_PARTS = 17;

const TABLES: readonly TableSpec[] = [
  { goFile: 'japanese.go', goVar: 'japaneseCategoryTable', tsName: 'japaneseLead' },
  ...Array.from({ length: CORE_PARTS }, (_, index) => ({
    goFile: `category_core_${index + 1}.go`,
    goVar: `coreCategoryTable${index + 1}`,
    tsName: `core${index + 1}`,
  })),
  { goFile: 'japanese.go', goVar: 'japaneseTrailCategoryTable', tsName: 'japaneseTrail' },
  { goFile: 'chinese.go', goVar: 'chineseCategoryTable', tsName: 'chinese' },
  { goFile: 'german.go', goVar: 'germanCategoryTable', tsName: 'german' },
  { goFile: 'dutch.go', goVar: 'dutchCategoryTable', tsName: 'dutch' },
  { goFile: 'danish.go', goVar: 'danishCategoryTable', tsName: 'danish' },
  { goFile: 'spanish.go', goVar: 'spanishCategoryTable', tsName: 'spanish' },
  { goFile: 'portuguese.go', goVar: 'portugueseCategoryTable', tsName: 'portuguese' },
];

const ENTRY = /^\s*\{("(?:[^"\\]|\\.)*"),\s*("(?:[^"\\]|\\.)*"|categoryNone)\},?\s*(?:\/\/.*)?$/;
const CATEGORY_NONE = '-';

export function extractTable(source: string, goVar: string): [string, string][] {
  const start = source.indexOf(`var ${goVar} = []aliasEntry{`);
  if (start < 0) throw new Error(`table ${goVar} not found`);
  const lines = source.slice(start).split('\n').slice(1);
  const entries: [string, string][] = [];
  for (const line of lines) {
    if (/^\}/.test(line)) return entries;
    const trimmed = line.trim();
    if (trimmed === '' || trimmed.startsWith('//')) continue;
    const match = ENTRY.exec(line);
    if (!match) throw new Error(`unparsed line in ${goVar}: ${line}`);
    const alias = JSON.parse(match[1]) as string;
    const canonical =
      match[2] === 'categoryNone' ? CATEGORY_NONE : (JSON.parse(match[2]) as string);
    entries.push([alias, canonical]);
  }
  throw new Error(`table ${goVar} not terminated`);
}

const HEADER = `// GENERATED by generateTables.ts — do not edit by hand.
// Source: freehire internal/dict/classify (https://github.com/strelov1/freehire),
// MIT License, Copyright (c) 2026 freehire contributors. See NOTICE in the repo root.
`;

function render(spec: TableSpec, entries: readonly [string, string][]): string {
  const body = entries
    .map(([alias, canonical]) => `  [${quote(alias)}, ${quote(canonical)}],`)
    .join('\n');
  return `${HEADER}// ${spec.goFile} ${spec.goVar}: ${entries.length} entries, declaration order.
import type { AliasEntry } from '../aliasEntry';

export const ${spec.tsName}: readonly AliasEntry[] = [
${body}
];
`;
}

function quote(text: string): string {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r/g, '\\r').replace(/\n/g, '\\n')}'`;
}

function main(classifyDir: string | undefined): void {
  if (!classifyDir) throw new Error('usage: generateTables.ts <freehire>/internal/dict/classify');
  const outDir = join(dirname(fileURLToPath(import.meta.url)), 'generated');
  mkdirSync(outDir, { recursive: true });
  for (const spec of TABLES) {
    const entries = extractTable(readFileSync(join(classifyDir, spec.goFile), 'utf8'), spec.goVar);
    writeFileSync(join(outDir, `${spec.tsName}.ts`), render(spec, entries));
    process.stdout.write(`${spec.tsName}: ${entries.length}\n`);
  }
}

main(process.argv[2]);
