import { describe, expect, it } from 'vitest';
import { isFinishedReply } from './coachReplyShape';

describe('законченная реплика консультанта (B511 Д6)', () => {
  it.each([
    ['ответ из снимка прода, оборванный посреди фразы', 'Её использование на первом этапе повышает риск кажущейся'],
    ['оборванный на запятой', 'Сервис вырос с 91 до 97 %, но в письме этого нет,'],
    ['пустышка вместо ответа', 'Вы спрашиваете...?'],
    ['пустая строка', '   '],
  ])('%s — не закончена', (_label, message) => {
    expect(isFinishedReply(message)).toBe(false);
  });

  it.each([
    ['точка', 'Поставьте результат в начало письма.'],
    ['вопрос', 'Какой результат вы хотите показать первым?'],
    ['кавычка после точки', 'Добавьте фразу: «Сервис вырос с 91 до 97 %.»'],
    ['число с процентом', 'Главный результат в письме сейчас: рост с 91 до 97 %'],
    ['короткий законченный ответ', 'Да, это подходит.'],
  ])('%s — закончена', (_label, message) => {
    expect(isFinishedReply(message)).toBe(true);
  });
});
