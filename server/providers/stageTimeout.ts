/**
 * Потолок одной ступени очереди провайдеров.
 *
 * Решение владельца 2026-09-03 (B180): ступень, которая думает слишком долго,
 * кандидату уже не помогает — за её спиной очередь, и лучше отдать ход
 * следующей, чем ждать. Клиентские потолки стояли в 60–90 секунд, поэтому одна
 * медленная ступень съедала весь ход.
 *
 * 2026-09-04 (B197, решение владельца «потолок ожидания надо увеличить»):
 * тридцати секунд оказалось мало. Замер B185 показал здоровые попытки до
 * 45.2 с (`nemotron`) и 33.4 с (`gpt-5.6-luna`) — прежний потолок обрывал
 * работающую ступень. Пятьдесят секунд покрывают самую медленную здоровую
 * попытку замера, по-прежнему отсекают патологию (85 с у `gemini-3.5-flash`,
 * 120 с у `openrouter/free`) и оставляют ход из трёх ролей (150 с в худшем
 * случае) внутри `requestTimeout` сервера в 190 секунд.
 *
 * Ступень тратит эти секунды один раз: повтор внутри клиента удваивал бы
 * бюджет молча. Повтор — это и есть следующая ступень очереди.
 */
