export type IconName = keyof typeof ICONS | 'starf';

export interface IconProps {
  readonly name: IconName;
  readonly className?: string;
  /** Подпись для чтения с экрана; без неё значок декоративный. */
  readonly label?: string;
}

export function Icon({ name, className, label }: IconProps) {
  const filled = name === 'starf';
  const Component = filled ? ICONS.star : ICONS[name];
  const classes = className ? `ico ${className}` : 'ico';
  return label ? (
    <Component
      className={classes}
      weight={filled ? 'fill' : 'regular'}
      role="img"
      aria-label={label}
    />
  ) : (
    <Component className={classes} weight={filled ? 'fill' : 'regular'} aria-hidden="true" />
  );
}
