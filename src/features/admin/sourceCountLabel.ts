/**
 * Сколько источников назвать в подписи — и называть ли вообще (B212).
 *
 * «18+» стояло литералом в разметке с тех пор, когда источников действительно
 * было восемнадцать. Их стало 195, литерал остался, и экран обещал «из 18+
 * каналов» ровно там, где рядом честно считал «159 из 195» (PRB-024).
 *
 * `null` означает «список ещё не пришёл»: числа тогда нет вовсе. Ноль — это
 * ответ, а не незнание, и подменять одно другим нельзя.
 */
export function sourceCountLabel(sources: readonly unknown[] | undefined): string | null {
  if (!sources) return null;
  return String(sources.length);
}
